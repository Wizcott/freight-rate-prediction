from pathlib import Path
import json

import pandas as pd
import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt

from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Image,
    Table,
    TableStyle
)

from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib import colors

ROOT = Path(__file__).resolve().parent

with open(ROOT / "metrics.json", "r") as file:
    metrics = json.load(file)


december = pd.read_csv(
    ROOT / "data/december_chart_inputs.csv"
)


plt.figure(figsize=(10, 4))

plt.plot(
    pd.to_datetime(december["date"]),
    december["predicted_rate"],
    marker="o",
    markersize=3
)

plt.title(
    "December 2025 Predicted Freight Rates — Independent Preview"
)

plt.ylabel("Predicted Rate ($)")
plt.xlabel("Date")

plt.xticks(rotation=35)

plt.tight_layout()

plt.savefig(
    ROOT / "december_preview.png",
    dpi=160
)

plt.close()

styles = getSampleStyleSheet()

story = []


# Helper function for adding text
def add(text, style="BodyText"):

    story.append(
        Paragraph(text, styles[style])
    )

    story.append(
        Spacer(1, 12)
    )


add(
    "Freight Rate Prediction — Technical Assessment",
    "Title"
)

add("Scope and Data", "Heading2")

add(
    "Labeled development set: 48,000 loads dated "
    "January 1–October 31, 2025. "
    "Final validation set: 12,000 loads. "
    "December chart inputs: 31 daily rows. "
    "Target variable: posted_rate. "
    "The validation dataset has no target labels."
)


add("Data Quality and Preprocessing", "Heading2")

add(
    "The development data has 300 missing weight values "
    "and 374 missing market_index values. "
    "CatBoost handles missing numerical values natively. "
    "Categorical features are standardized as strings. "
    "Date fields are parsed and converted into numerical "
    "calendar features. "
    "Missing fields in December, including coordinates, "
    "market_index and quote_signal, are left missing "
    "rather than estimated. "
    "No labeled target data from validation or December "
    "is used during training."
)

add("Features and Model", "Heading2")

add(
    "The selected model is CatBoost Regression, "
    "using gradient-boosted decision trees. "
    "The configuration includes 550 iterations, "
    "tree depth 8, learning rate 0.055, "
    "and L2 regularization of 5."
)

add(
    "Engineered features include pickup location, "
    "delivery location, equipment type, "
    "origin-destination lane, distance, "
    "squared distance, weight, weight per mile, "
    "geographical coordinates where available, "
    "market index, quote signal, interaction features, "
    "and calendar features."
)

add(
    "CatBoost was selected because it supports "
    "mixed categorical and numerical data "
    "and handles missing numerical values."
)


add("Chronological Holdout Validation", "Heading2")

add(
    "The labeled development data was split "
    "chronologically to evaluate future-period "
    "prediction performance."
)

add(
    "Training period: January–September 2025 "
    "(43,147 records). "
    "Holdout validation period: October 2025 "
    "(4,853 records)."
)

add(
    "A chronological split was selected instead "
    "of a random split because the task involves "
    "predicting future freight rates. "
    "This approach reduces temporal leakage "
    "and better represents real-world forecasting."
)

add(
    "After evaluating the model, the same configuration "
    "was retrained using all 48,000 labeled records "
    "before generating the final predictions."
)


add("Model Evaluation Results", "Heading2")

rows = [
    ["Metric", "October 2025 Holdout"],
    ["MAE", f"{metrics['MAE']:.2f}"],
    ["RMSE", f"{metrics['RMSE']:.2f}"],
    ["R²", f"{metrics['R2']:.4f}"],
    ["WAPE", f"{metrics['WAPE']:.2%}"]
]

table = Table(
    rows,
    colWidths=[180, 190]
)

table.setStyle(
    TableStyle([
        (
            "BACKGROUND",
            (0, 0),
            (-1, 0),
            colors.HexColor("#DDEBF5")
        ),
        (
            "GRID",
            (0, 0),
            (-1, -1),
            0.3,
            colors.grey
        ),
        (
            "PADDING",
            (0, 0),
            (-1, -1),
            8
        )
    ])
)

story.append(table)

story.append(Spacer(1, 16))

add(
    "December Predictions — Official Scorer Chart",
    "Heading2"
)

add(
    "The following chart was generated by the official "
    "score.py script after validating all 12,000 final "
    "predictions and all 31 December predictions."
)

add(
    "December inputs contain fewer features than "
    "the training and validation datasets. "
    "Therefore, prediction performance may differ "
    "from the October holdout results."
)

add(
    "Final hidden validation metrics will be "
    "calculated by Spotter after submission."
)

chart_path = (
    ROOT / "scorer_results/candidate_december.png"
)

story.append(
    Image(
        str(chart_path),
        width=480,
        height=215
    )
)

story.append(Spacer(1, 12))

add("Reproducibility", "Heading2")

add(
    "The project can be reproduced by installing "
    "the dependencies in requirements.txt, "
    "running train.py to train the model and "
    "generate predictions, and executing score.py "
    "to validate the output files."
)

add(
    "Final validation predictions are matched "
    "to the required template using load_id "
    "and checked for completeness."
)

report_path = ROOT / "report.pdf"

document = SimpleDocTemplate(
    str(report_path),
    pagesize=(595, 842),
    rightMargin=50,
    leftMargin=50,
    topMargin=45,
    bottomMargin=45
)

document.build(story)

print("Assessment report generated successfully!")

print(f"Saved to: {report_path}")